// 固定顺序打乱（每次打开顺序都一样，词表不改就不会变）
function wdShuffle(a, seed){
  const r = a.slice(); let t = seed >>> 0;
  const rnd = () => { t = (t + 0x6D2B79F5) >>> 0; let x = Math.imul(t ^ (t >>> 15), 1 | t); x ^= x + Math.imul(x ^ (x >>> 7), 61 | x); return ((x ^ (x >>> 14)) >>> 0) / 4294967296; };
  for (let i = r.length - 1; i > 0; i--){ const j = Math.floor(rnd() * (i + 1)); [r[i], r[j]] = [r[j], r[i]]; }
  return r;
}
function wdMix(a, b){ const r = []; for (let i = 0; i < Math.max(a.length, b.length); i++){ if (i < a.length) r.push(a[i]); if (i < b.length) r.push(b[i]); } return r; }
const WD_LIST = {};
function wdList(g){
  if (WD_LIST[g]) return WD_LIST[g];
  const tag = k => WORDS[k].map(w => [...w, k]);
  const gen = wdShuffle(tag('gen'), 7);
  const sp = g ? wdShuffle(tag(g), 11) : wdShuffle([...tag('art'), ...tag('sci'), ...tag('hum')], 13);
  return WD_LIST[g] = wdMix(gen, sp);
}
