// 例句：{漢字|かんじ} 显示成注音；这个词本身标粗（动词变形时标词干，例：描く → 描いた）
const wdPlain = ex => ex.replace(/\{([^|}]+)\|[^}]+\}/g, '$1');
function wdEx(ex, w){
  const seg = []; ex.replace(/\{([^|}]+)\|([^}]+)\}|[^{]+/g, (m, b, r) => { seg.push(b ? {b, r} : {t: m}); return m; });
  let hit = '';
  for (let k = w.length; k >= 1 && !hit; k--){
    const p = w.slice(0, k);
    if (k < w.length && /^[\u3040-\u309f]+$/.test(p)) break;
    if (seg.some(x => x.t && x.t.includes(p))) hit = p;
  }
  let done = false;
  return seg.map(x => {
    if (x.b) return `<ruby>${esc(x.b)}<rt>${esc(x.r)}</rt></ruby>`;
    const i = hit && !done ? x.t.indexOf(hit) : -1;
    if (i < 0) return esc(x.t);
    done = true; return `${esc(x.t.slice(0, i))}<b>${esc(hit)}</b>${esc(x.t.slice(i + hit.length))}`;
  }).join('');
}
