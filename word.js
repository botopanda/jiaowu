function wdGroup(s){
  const t = [s.direction, s.track].filter(Boolean).join(' ');
  if (/美术|艺术|美術|芸術|漫画|动画|動画|アニメ|插画|イラスト|写真|摄影|影像|映像|电影|映画|设计|デザイン|绘画|游戏|ゲーム/.test(t)) return 'art';
  if (/理科|理工|理系|工学|数学|物理|化学|生物|医|药|薬|情报|信息|计算机/.test(t)) return 'sci';
  if (/文科|文系|经济|経済|经营|経営|商学|法学|社会|国际|国際|文学|教育|心理|政治|历史|歴史/.test(t)) return 'hum';
  const sj = DB.courses.filter(c => c.student_id === s.id).map(c => c.subject);
  if (sj.some(x => x !== '不分科目' && ART_SUBJECTS.includes(x))) return 'art';
  if (sj.some(x => ['物理', '化学', '生物'].includes(x))) return 'sci';
  if (sj.includes('文综')) return 'hum';
  return '';
}
// 例句里把这个词标粗（动词变形时标词干，例：描く → 描いた）
function wdMark(ex, w){
  for (let k = w.length; k >= 1; k--){
    const p = w.slice(0, k);
    if (k < w.length && /^[぀-ゟ]+$/.test(p)) break;
    const i = ex.indexOf(p);
    if (i >= 0) return `${esc(ex.slice(0, i))}<b>${esc(p)}</b>${esc(ex.slice(i + p.length))}`;
  }
  return esc(ex);
}
function sWordCard(s){
  WD_SID = s.id;
  const list = wdList(wdGroup(s)), day = Math.floor(Date.parse(TODAY + 'T00:00:00Z') / 86400000);
  const [w, r, m, ex, zh, g] = list[(day + (S.wdOff || 0)) % list.length];
  return `<section class="card wd-card" id="wd-card"><div class="row"><h3 class="sh-h" style="margin-right:auto">${S.wdOff ? '再来一个' : '今日单词'}</h3><span class="tag mute">${WD_TAG[g]}</span></div>
    <div class="wd-head"><b class="wd-w" lang="ja">${esc(w)}</b>${r ? `<span class="wd-r" lang="ja">${esc(r)}</span>` : ''}</div>
    <div class="wd-m">${esc(m)}</div>
    <div class="wd-ex"><div class="wd-ja" lang="ja">${wdMark(ex, w)}</div><div class="wd-zh">${esc(zh)}</div></div>
    <div class="row" style="justify-content:flex-end"><button class="btn sm" data-act="wd-next">再看一个 ›</button></div></section>`;
}
document.addEventListener('click', e => {
  const a = e.target.closest('[data-act="wd-next"]'); if (!a || !WD_SID) return;
  S.wdOff = (S.wdOff || 0) + 1;
  const el = document.getElementById('wd-card'); if (el) el.outerHTML = sWordCard(stu(WD_SID));
});
